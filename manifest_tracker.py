import glob
import json
import os


REGISTRY_PATH = "results/outputs_registry.json"
MANIFEST_PATH = "OUTPUTS_MANIFEST.md"


def _format_size(size_bytes):
    if size_bytes < 1024:
        return f"{size_bytes} B"
    elif size_bytes < 1024 * 1024:
        return f"{size_bytes / 1024:.1f} KB"
    else:
        return f"{size_bytes / (1024 * 1024):.1f} MB"


def _extract_metrics(run_data):
    player_metric = "N/A"
    ball_metric = "N/A"
    modules = run_data.get("modules", [])

    for m in modules:
        m_name = m.get("module")
        stats = m.get("stats", {})
        if m_name == "players":
            mean_p = stats.get("mean_players_per_frame", 0.0)
            tracked_cnt = stats.get("players_tracked", 0)
            player_metric = f"{mean_p:.1f}/4 ({tracked_cnt} slots)"
        elif m_name == "ball":
            det_rate = stats.get("detection_rate", 0.0)
            found = stats.get("frames_with_ball", 0)
            occl = stats.get("occluded_recovered_frames", 0)
            if occl > 0:
                ball_metric = f"{det_rate * 100:.1f}% ({found}f, +{occl} net)"
            else:
                ball_metric = f"{det_rate * 100:.1f}% ({found} frames)"

    return player_metric, ball_metric


def load_registry(registry_path=REGISTRY_PATH):
    if os.path.exists(registry_path):
        try:
            with open(registry_path) as f:
                return json.load(f)
        except Exception:
            pass
    return {"runs": []}


def save_registry(registry, registry_path=REGISTRY_PATH):
    os.makedirs(os.path.dirname(registry_path), exist_ok=True)
    with open(registry_path, "w") as f:
        json.dump(registry, f, indent=2)


def generate_manifest_markdown(registry, manifest_path=MANIFEST_PATH):
    runs = registry.get("runs", [])
    # Sort latest first
    runs_sorted = sorted(runs, key=lambda r: r.get("date", ""), reverse=True)

    total_runs = len(runs_sorted)
    latest_run = runs_sorted[0]["date"] if runs_sorted else "None"
    total_outputs_exist = sum(1 for r in runs_sorted if os.path.exists(r.get("output_video", "")))

    lines = [
        "# 🎬 Pickleball Vision AI - Outputs Tracker & Manifest",
        "",
        "This file automatically tracks every output video generated by the pipeline for both new and previously processed clips. It provides direct clickable links, quality benchmarks, and execution history.",
        "",
        "---",
        "",
        "## 📊 Quick Dashboard",
        f"- **Total Pipeline Runs Recorded**: `{total_runs}`",
        f"- **Available Output Videos**: `{total_outputs_exist}`",
        f"- **Latest Execution**: `{latest_run}`",
        "",
        "---",
        "",
        "## 📁 Tracked Output Videos",
        "",
        "| Date / Time | Output Video | Input Clip | Resolution & Frames | Modules | Player Tracking | Ball Tracking | Total Latency | File Size | Status |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]

    for r in runs_sorted:
        date = r.get("date", "N/A")
        out_vid = r.get("output_video", "N/A")
        in_clip = r.get("clip", "N/A")
        res = r.get("resolution", "N/A")
        frames = r.get("frames", 0)
        fps = r.get("fps", 30.0)
        mods = "+".join(r.get("modules_on", []))
        total_s = r.get("total_s", 0.0)
        compute_fps = round(frames / max(0.01, total_s), 1)

        p_metric, b_metric = _extract_metrics(r)

        file_exists = os.path.exists(out_vid) if out_vid else False
        if file_exists:
            size_str = _format_size(os.path.getsize(out_vid))
            status_badge = "✅ Playable"
            vid_link = f"[`{os.path.basename(out_vid)}`]({out_vid})"
        else:
            size_str = "N/A"
            status_badge = "⚠️ File Missing"
            vid_link = f"`{os.path.basename(out_vid)}`"

        clip_name = os.path.basename(in_clip)
        lines.append(
            f"| `{date}` | {vid_link} | `{clip_name}` | {res} ({frames}f @ {fps:.0f}fps) | `{mods}` | {p_metric} | {b_metric} | {total_s:.1f}s ({compute_fps} FPS) | {size_str} | {status_badge} |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 🔍 Detailed Run Records",
        "",
    ])

    for idx, r in enumerate(runs_sorted):
        out_vid = r.get("output_video", "N/A")
        clip = r.get("clip", "N/A")
        p_metric, b_metric = _extract_metrics(r)

        lines.append(f"### Run {total_runs - idx}: `{os.path.basename(out_vid)}` ({r.get('date')})")
        lines.append(f"- **Input Source**: `{clip}` ({r.get('resolution')}, {r.get('frames')} frames, {r.get('clip_seconds')}s)")
        lines.append(f"- **Output Location**: `{out_vid}`")
        lines.append(f"- **Hardware Used**: `{r.get('device', 'CPU')}`")
        lines.append(f"- **Active Modules**: `{', '.join(r.get('modules_on', []))}`")
        lines.append(f"- **Player Quality**: `{p_metric}`")
        lines.append(f"- **Ball Quality**: `{b_metric}`")
        lines.append(f"- **Compute Time**: Read: `{r.get('read_s', 0)}s` | Compute: `{r.get('compute_s', 0)}s` | Render: `{r.get('render_s', 0)}s` | Total: `{r.get('total_s', 0)}s`")
        lines.append("")

    with open(manifest_path, "w") as f:
        f.write("\n".join(lines) + "\n")


def update_manifest(summary, registry_path=REGISTRY_PATH, manifest_path=MANIFEST_PATH):
    """Updates registry and regenerates OUTPUTS_MANIFEST.md."""
    reg = load_registry(registry_path)

    # Check if duplicate run exists (same timestamp and output)
    existing_idx = None
    for i, r in enumerate(reg.get("runs", [])):
        if r.get("date") == summary.get("date") and r.get("output_video") == summary.get("output_video"):
            existing_idx = i
            break

    if existing_idx is not None:
        reg["runs"][existing_idx] = summary
    else:
        reg["runs"].append(summary)

    save_registry(reg, registry_path)
    generate_manifest_markdown(reg, manifest_path)


def backfill_history(runs_dir="results/runs", registry_path=REGISTRY_PATH, manifest_path=MANIFEST_PATH):
    """Scans results/runs/*.json to populate the manifest with all past runs."""
    reg = load_registry(registry_path)
    known = {(r.get("date"), r.get("output_video")) for r in reg.get("runs", [])}

    for json_file in sorted(glob.glob(os.path.join(runs_dir, "*.json"))):
        try:
            with open(json_file) as f:
                data = json.load(f)
            key = (data.get("date"), data.get("output_video"))
            if key not in known:
                reg["runs"].append(data)
                known.add(key)
        except Exception:
            pass

    save_registry(reg, registry_path)
    generate_manifest_markdown(reg, manifest_path)


def list_manifest(registry_path=REGISTRY_PATH):
    """Prints a clean summary table of all tracked outputs to the terminal."""
    reg = load_registry(registry_path)
    runs = sorted(reg.get("runs", []), key=lambda r: r.get("date", ""), reverse=True)
    if not runs:
        print("[manifest] No tracked outputs found yet.")
        return

    print("\n" + "=" * 90)
    print("TRACKED PIPELINE OUTPUTS (from OUTPUTS_MANIFEST.md)")
    print("=" * 90)
    header = f"{'DATE':<20} {'CLIP':<18} {'RESOLUTION':<12} {'FRAMES':<8} {'OUTPUT FILE':<30}"
    print(header)
    print("-" * 90)
    for r in runs:
        date = r.get("date", "")[:19]
        clip = os.path.basename(r.get("clip", ""))[:16]
        res = r.get("resolution", "")[:10]
        frames = str(r.get("frames", ""))
        out = os.path.basename(r.get("output_video", ""))[:28]
        print(f"{date:<20} {clip:<18} {res:<12} {frames:<8} {out:<30}")
    print("=" * 90 + "\n")


if __name__ == "__main__":
    backfill_history()
    list_manifest()
    print(f"Generated {MANIFEST_PATH}")
